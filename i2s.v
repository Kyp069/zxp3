module i2s
//-------------------------------------------------------------------------------------------------
(
	input  wire       clock,
	input  wire[15:0] l,
	input  wire[15:0] r,
	output reg        ck,
	output reg        ws,
	output reg        sd
);
//-------------------------------------------------------------------------------------------------

reg[8:0] ce;
always @(negedge clock) ce <= ce+1'd1;

wire ce4 = &ce[3:0];
wire ce5 = &ce[4:0];
wire ce9a = ce[8] & ce[7] & ce[6] &  ce[5] & ce[4] & ce[3] & ce[2] & ce[1] & ce[0];
wire ce9b = ce[8] & ce[7] & ce[6] & ~ce[5] & ce[4] & ce[3] & ce[2] & ce[1] & ce[0];

reg[14:0] sr;

always @(posedge clock) if(ce4) ck <= ~ck;
always @(posedge clock) if(ce9b) ws <= ~ws;
always @(posedge clock) if(ce9a) { sd, sr } <= ws ? r : l; else if(ce5) { sd, sr } <= { sr, 1'b0 };

//-------------------------------------------------------------------------------------------------
endmodule
//-------------------------------------------------------------------------------------------------

//-------------------------------------------------------------------------------------------------
module i2s_decoder
//-------------------------------------------------------------------------------------------------
(
	input  wire       clock,
	
	output reg [15:0] left,
	output reg [15:0] right,

	input  wire       ck,
	input  wire       ws,
	input  wire       d
);
//-------------------------------------------------------------------------------------------------

reg[1:0] cks;
always @(posedge clock) cks <= { cks[0], ck };

//-------------------------------------------------------------------------------------------------

reg ckd, ckn, ckp;
always @(posedge clock) begin ckd <= cks[1]; ckn <= !cks[1] && ckd; ckp <= cks[1] && !ckd; end

reg wsd, wst;
always @(posedge clock) if(ckn) begin wsd <= ws; wst = ws != wsd; end

//-------------------------------------------------------------------------------------------------

reg[16:0] sr = 17'd1;
always @(posedge clock) begin
	if(ckp) if(!sr[16]) sr <= { sr[15:0], d };
	if(ckn)
		if(wst) begin
			sr <= 17'd1;
			if(ws) right <= sr[15:0]; else left <= sr[15:0];
		end
end

//-------------------------------------------------------------------------------------------------
endmodule
